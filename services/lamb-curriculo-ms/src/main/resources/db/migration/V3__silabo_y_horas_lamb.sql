-- Estructura del silabo y de las horas del curso como en el LAMB real de la UPeU

-- Horas: HNP (no presenciales), HAA (aprendizaje autonomo) y teoria/practica sincronas y asincronas
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_no_presenciales INTEGER CHECK (horas_no_presenciales >= 0);
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_aprendizaje_autonomo INTEGER CHECK (horas_aprendizaje_autonomo >= 0);
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_teoria_sincronas INTEGER CHECK (horas_teoria_sincronas >= 0);
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_teoria_asincronas INTEGER CHECK (horas_teoria_asincronas >= 0);
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_practica_sincronas INTEGER CHECK (horas_practica_sincronas >= 0);
ALTER TABLE distribuciones_horas ADD COLUMN IF NOT EXISTS horas_practica_asincronas INTEGER CHECK (horas_practica_asincronas >= 0);

-- Silabo base: competencias, resultado y producto, recursos y referencias por tipo
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS id_competencia_especifica BIGINT REFERENCES competencias_especificas(id);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS id_competencia_general BIGINT REFERENCES competencias_generales(id);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS resultado_aprendizaje VARCHAR(1000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS producto_academico VARCHAR(255);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS descripcion_producto VARCHAR(1000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS recursos VARCHAR(2000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS referencias_basicas VARCHAR(2000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS referencias_complementarias VARCHAR(2000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS enlaces_internet VARCHAR(2000);
ALTER TABLE silabos_base ADD COLUMN IF NOT EXISTS nota_minima_aprobatoria NUMERIC(5,2) CHECK (nota_minima_aprobatoria BETWEEN 0 AND 20);

-- Unidad de aprendizaje: resultado, producto y criterios de evaluacion del producto
ALTER TABLE unidades_aprendizaje ADD COLUMN IF NOT EXISTS resultado_aprendizaje VARCHAR(1000);
ALTER TABLE unidades_aprendizaje ADD COLUMN IF NOT EXISTS producto VARCHAR(255);
ALTER TABLE unidades_aprendizaje ADD COLUMN IF NOT EXISTS descripcion_producto VARCHAR(1000);
ALTER TABLE unidades_aprendizaje ADD COLUMN IF NOT EXISTS criterios_evaluacion VARCHAR(2000);

-- Dimensiones numeradas de cada competencia (general o especifica)
CREATE TABLE IF NOT EXISTS dimensiones_competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_competencia VARCHAR(20) NOT NULL CHECK (tipo_competencia IN ('GENERAL', 'ESPECIFICA')),
    id_competencia BIGINT NOT NULL,
    numero INTEGER NOT NULL CHECK (numero >= 1),
    descripcion VARCHAR(500) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_dimensiones_competencia UNIQUE (tipo_competencia, id_competencia, numero)
);
