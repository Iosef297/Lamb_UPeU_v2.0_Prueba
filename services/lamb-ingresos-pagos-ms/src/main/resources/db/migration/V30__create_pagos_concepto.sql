CREATE TABLE IF NOT EXISTS pagos_concepto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_estudiante VARCHAR(36) NOT NULL,
    id_concepto_pago BIGINT NOT NULL REFERENCES conceptos_pago(id),
    id_metodo_pago BIGINT NOT NULL REFERENCES metodos_pago(id),
    id_sesion_caja BIGINT REFERENCES sesiones_caja(id),
    monto NUMERIC(12,2) NOT NULL,
    observacion VARCHAR(255),
    fecha_pago TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);
