ALTER TABLE sesiones_clase ADD COLUMN IF NOT EXISTS adjunto_url VARCHAR(500);

-- Conformidad del estudiante con el silabo del grupo
CREATE TABLE IF NOT EXISTS conformidades_silabo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL REFERENCES grupos(id),
    id_persona BIGINT NOT NULL,
    fecha TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_conformidades_silabo UNIQUE (id_grupo, id_persona)
);
