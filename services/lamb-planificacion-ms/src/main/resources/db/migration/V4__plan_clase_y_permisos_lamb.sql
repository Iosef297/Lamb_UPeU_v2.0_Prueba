ALTER TABLE sesiones_clase ADD COLUMN IF NOT EXISTS horas_practica INTEGER CHECK (horas_practica >= 0);
ALTER TABLE sesiones_clase ADD COLUMN IF NOT EXISTS horas_autonomas INTEGER CHECK (horas_autonomas >= 0);
ALTER TABLE sesiones_clase ADD COLUMN IF NOT EXISTS actividad_practica VARCHAR(1000);
