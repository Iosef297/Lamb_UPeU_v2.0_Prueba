-- Horario: rango de fechas en que rige y tipo de sesion
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS fecha_inicio DATE;
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS fecha_fin DATE;
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS tipo VARCHAR(20) CHECK (tipo IN ('TEORIA', 'PRACTICA'));
ALTER TABLE horarios_grupo ADD CONSTRAINT ck_horarios_grupo_fechas CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio);

-- Permiso del grupo: el docente puede editar el silabo (el admin lo abre y lo cierra)
ALTER TABLE grupos ADD COLUMN IF NOT EXISTS puede_editar_silabo BOOLEAN NOT NULL DEFAULT true;

