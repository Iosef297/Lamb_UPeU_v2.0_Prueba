-- H5: franjas pedagogicas fijas (17 por dia). Se marcan franjas, no horas libres.
-- F0..F9 verificadas en el Portal del Alumno (Jue 09:20-13:00 = F2..F5, Mar 07:30-11:10 = F0..F3, F9 termina 16:50).
CREATE TABLE IF NOT EXISTS franjas_horarias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden       INTEGER     NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL,
    turno       VARCHAR(10) NOT NULL,
    CONSTRAINT uk_franjas_orden UNIQUE (orden),
    CONSTRAINT ck_franjas_orden CHECK (orden BETWEEN 0 AND 16),
    CONSTRAINT ck_franjas_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_franjas_turno CHECK (turno IN ('MANANA', 'TARDE', 'NOCHE'))
);
