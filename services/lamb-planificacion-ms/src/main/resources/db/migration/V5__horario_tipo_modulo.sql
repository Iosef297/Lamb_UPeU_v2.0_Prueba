ALTER TABLE horarios_grupo ALTER COLUMN tipo_horario SET NOT NULL;
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS numero_subgrupo INTEGER CHECK (numero_subgrupo BETWEEN 1 AND 20);

-- Docente que dicta el bloque y modulo al que pertenece (ambos opcionales)
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS id_asignacion_docente BIGINT REFERENCES asignaciones_docente(id) ON DELETE SET NULL;
ALTER TABLE horarios_grupo ADD COLUMN IF NOT EXISTS id_modulo BIGINT REFERENCES modulos_periodo(id);

-- Ambiente "Por confirmar"
ALTER TABLE horarios_grupo ALTER COLUMN id_ambiente DROP NOT NULL;

-- El cruce de ambiente ahora exige que los rangos de fechas se superpongan (null = todo el periodo)
ALTER TABLE horarios_grupo DROP CONSTRAINT IF EXISTS ex_horarios_grupo_cruce_ambiente;
ALTER TABLE horarios_grupo ADD CONSTRAINT ex_horarios_grupo_cruce_ambiente EXCLUDE USING gist (
    id_ambiente WITH =,
    id_periodo WITH =,
    dia_semana WITH =,
    tsrange(DATE '2000-01-01' + hora_inicio, DATE '2000-01-01' + hora_fin) WITH &&,
    daterange(COALESCE(fecha_inicio, '-infinity'::date), COALESCE(fecha_fin, 'infinity'::date), '[]') WITH &&
) WHERE (activo);

