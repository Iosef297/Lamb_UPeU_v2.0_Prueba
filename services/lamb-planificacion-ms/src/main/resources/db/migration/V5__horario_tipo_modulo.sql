-- Horario como en el LAMB real (verificado con 37 bloques del Portal del Alumno):
--   tipo T / T1 / P1 = Teoria o Practica + numero de subgrupo; cada bloque lo dicta un docente del grupo;
--   el modulo ("Regular - Pregrado", "Modular 1 - Pregrado") agrupa bloques con sus fechas;
--   el ambiente puede quedar "Por confirmar"; un choque solo cuenta si los rangos de fechas se cruzan.

-- Modulos del periodo
CREATE TABLE IF NOT EXISTS modulos_periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_periodo BIGINT NOT NULL REFERENCES periodos_academicos(id),
    nombre VARCHAR(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_modulos_periodo UNIQUE (id_periodo, nombre),
    CONSTRAINT ck_modulos_periodo_fechas CHECK (fecha_fin >= fecha_inicio)
);

-- Tipo: TEORIA / PRACTICA + numero de subgrupo (V4 lo habia creado como "tipo")
